<?php
/**
 * Run under the baseline PHP (5.6) to create tests/fixtures/packets.php.
 * Usage: php tests/tools/capture_packets.php
 */

error_reporting(E_ALL & ~E_DEPRECATED & ~E_USER_DEPRECATED & ~E_NOTICE & ~E_USER_NOTICE);

require __DIR__ . '/../bootstrap.php';
require __DIR__ . '/../packet_cases.php';

$fixtures = array();
$failures = array();

foreach (test_packet_classes() as $class) {
    try {
        $packet = test_packet_make($class);
        ob_start();
        $bytes = $packet->pack();
        ob_end_clean();
        $fixtures[$class] = bin2hex($bytes);
    } catch (Exception $e) {
        if (ob_get_level() > 0) {
            ob_end_clean();
        }
        $failures[$class] = $e->getMessage();
    }
}

if ($failures) {
    fwrite(STDERR, "Capture failed:\n");
    foreach ($failures as $class => $message) {
        fwrite(STDERR, "  {$class}: {$message}\n");
    }
    exit(1);
}

$body = "<?php\n\n// Generated by tests/tools/capture_packets.php on PHP " . PHP_VERSION . ".\n"
      . "// Do not regenerate without reviewing the byte diff.\n\nreturn "
      . var_export($fixtures, true) . ";\n";

file_put_contents(__DIR__ . '/../fixtures/packets.php', $body);

$dump = '';
foreach ($fixtures as $class => $hex) {
    $dump .= $class . ' ' . $hex . "\n";
}
file_put_contents(__DIR__ . '/../fixtures/packets.dump', $dump);

echo 'Captured ' . count($fixtures) . " packets on PHP " . PHP_VERSION . "\n";
